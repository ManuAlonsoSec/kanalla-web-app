// ──────────────────────────────────────────────────────────────────────────────
// set-env.mjs  —  Pre-build script for Vercel
//
// Reads the three Vercel environment variables and writes both Angular
// environment files so they are available to `ng build`.
//
// Run via:  node set-env.mjs   (before npm run build)
// ──────────────────────────────────────────────────────────────────────────────
import { writeFileSync, mkdirSync } from 'fs';
import { dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const url    = process.env.NG_SUPABASE_URL      ?? '';
const key    = process.env.NG_SUPABASE_ANON_KEY ?? '';
const google = process.env.NG_GOOGLE_CLIENT_ID  ?? '';

// Fail the build immediately if the essential vars are missing.
if (!url || !key) {
  console.error(
    '\n❌  ERROR: NG_SUPABASE_URL and NG_SUPABASE_ANON_KEY must be set in ' +
    'Vercel → Project Settings → Environment Variables.\n'
  );
  process.exit(1);
}

const dir = `${__dirname}/src/environments`;
mkdirSync(dir, { recursive: true });

const prod = `\
// AUTO-GENERATED by set-env.mjs — do not edit manually.
export const environment = {
  production: true,
  supabaseUrl: '${url}',
  supabaseAnonKey: '${key}',
  googleClientId: '${google}',
};\n`;

const dev = prod.replace('production: true', 'production: false');

writeFileSync(`${dir}/environment.prod.ts`, prod, 'utf8');
writeFileSync(`${dir}/environment.ts`,      dev,  'utf8');

console.log('✅  Environment files generated from Vercel env vars.');
